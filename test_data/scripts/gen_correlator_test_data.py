def desc_params(n_ants, n_bits, acc_len, demux):
    """xeng_descramble mask initialization (system_root.xml, Block 411)."""
    n, L, d = n_ants, acc_len, demux
    T = n // 2 + 1
    NV = n * T
    E = n * (n + 1) // 2
    W = 2 * n_bits + int(math.floor(math.log2(L))) + 1
    P = 1 << math.ceil(math.log2(W))
    dl = (L * n) // NV // d - 1
    DEL = max(dl, 0)
    CNT = d * E - 1 if DEL == 0 else d * E
    return dict(N=n, T=T, NV=NV, E=E, PIVOT=n // 2 * T + T * n // 4, W=W, P=P, OW=8 * P // d,
                D=d, DEL=DEL, CNT=CNT, DEL_BITS=max(1, math.ceil(math.log2(DEL + 1))),
                RD_BITS=math.ceil(math.log2(CNT + 1)), WA_BITS=math.ceil(math.log2(E)),
                K_START=math.ceil(3 * NV / 4), PULSE=math.ceil(n / 2) * L,
                TAPS_BITS=int(math.floor(math.log2(T))) + 1, ANT_BITS=math.ceil(math.log2(n)),
                VI_BITS=int(math.floor(math.log2(NV))) + 1)


def m_x_cast(w, p_, d, word):
    out = 0
    flip = 8 // d - 1
    for j in range(8):
        f = (word >> (((j ^ flip)) * w)) & ((1 << w) - 1)
        out |= u(s(f, w), p_) << ((7 - j) * p_)
    return out


def conj_swap(word, w):
    """{c3,c2,c1,c0} -> {conj c3, conj c2, conj c0, conj c1}, W-bit Wrap negate."""
    c = [(word >> (2 * w * i)) & ((1 << 2 * w) - 1) for i in range(4)]
    cj = [((x >> w) << w) | u(-s(x, w), w) for x in c]
    return (cj[3] << 6 * w) | (cj[2] << 4 * w) | (cj[0] << 2 * w) | cj[1]


class NegedgeDelay:
    def __init__(self, L):
        self.L, self.nb = L, math.ceil(math.log2(L + 1))
        self.prev = self.cnt = self.d1 = 0

    def out(self, x):
        return x | self.d1 | int(self.cnt <= self.L - 2)

    def step(self, x):
        ne = int(not x and self.prev)
        run = int(self.cnt <= self.L - 2)
        self.cnt = 0 if ne else ((self.cnt + 1) % (1 << self.nb) if run else self.cnt)
        self.prev = self.d1 = x


def m_write_ctrl(q, sync, data_in, xeng_valid, window_valid):
    """Structural model of write_ctrl. Returns dict of per-cycle outputs."""
    T, N, NV, E, PIV = q["T"], q["N"], q["NV"], q["E"], q["PIVOT"]
    w = q["W"]
    ned = NegedgeDelay(q["PULSE"])
    sync_d = win_prev = valid_in = rst = vld = 0
    dat = [0, 0]
    tap = line = element = 0
    ge = tap0 = 0
    c3, c2 = 0, PIV
    at_k = at_k_prev = 0
    out = dict(start_readout=[], write_addr=[], data_out=[], enable=[])
    for sy, x, xv, wv in zip(sync, data_in, xeng_valid, window_valid):
        rst_in = sync_d | (wv & (1 - win_prev))
        ned_out = ned.out(wv)
        tap_end = int(tap == T - 1)
        last = 1 - ge
        blank = tap0 & last
        out["write_addr"].append(c2 if last else c3)
        out["enable"].append(vld & (1 - blank))
        out["data_out"].append(conj_swap(dat[1], w) if last else dat[1])
        out["start_readout"].append(at_k & (1 - at_k_prev))
        # register updates (all from the values above)
        n_ge = int(tap >= (T - 1) - line)
        n_tap0 = int(tap == 0)
        n_c3 = 0 if rst else ((0 if c3 == PIV - 1 else c3 + 1) if (vld and not last) else c3)
        n_c2 = PIV if rst else ((PIV if c2 == E - 1 else c2 + 1)
                                if (last and not blank and vld) else c2)
        n_tap = 0 if rst_in else ((0 if tap == T - 1 else tap + 1) if (tap_end or valid_in) else tap)
        n_line = 0 if rst_in else ((0 if line == N - 1 else line + 1) if (tap_end and valid_in) else line)
        n_el = 0 if rst_in else ((0 if element == NV - 1 else element + 1) if valid_in else element)
        at_k_prev, at_k = at_k, int(element == q["K_START"])
        ge, tap0, c3, c2 = n_ge, n_tap0, n_c3, n_c2
        tap, line, element = n_tap, n_line, n_el
        vld, rst = valid_in, rst_in
        valid_in = ned_out & xv
        ned.step(wv)
        dat = [x, dat[0]]
        sync_d, win_prev = sy, wv
    return out


def m_read_ctrl(q, start):
    dly = rd = done = 0
    out = dict(read_addr=[], enable=[])
    for st in start:
        pace = int(dly >= q["DEL"])
        en = pace & (1 - done)
        at_end = int(rd >= q["CNT"])
        out["read_addr"].append(rd)
        out["enable"].append(en)
        dly = 0 if (st or pace) else (dly + 1) % (1 << q["DEL_BITS"])
        nrd = 0 if st else ((rd + 1) % (1 << q["RD_BITS"]) if en else rd)
        done = 0 if st else (at_end if at_end else done)
        rd = nrd
    return out


def m_xeng_descramble(q, ram_lat, acc, valid, sync, win_valid, stats=None):
    wc = m_write_ctrl(q, sync, acc, valid, win_valid)
    rc = m_read_ctrl(q, wc["start_readout"])
    d, ow, p_ = q["D"], q["OW"], q["P"]
    mem = [0] * (q["E"] + 1)
    rdata, collisions = 0, 0
    pipe = [0] * (ram_lat - 1)
    subp = [0] * ram_lat
    validp = [0] * ram_lat
    andp = [0] * ram_lat
    seen = 0
    out = dict(acc_out=[], valid_out=[], sync_out=[])
    for i in range(len(acc)):
        rd_out = pipe[-1] if pipe else rdata
        out["acc_out"].append((rd_out >> (subp[-1] * ow)) & ((1 << ow) - 1))
        out["valid_out"].append(validp[-1])
        out["sync_out"].append(andp[-1])
        st = wc["start_readout"][i]
        ra = rc["read_addr"][i]
        new_rdata = mem[(ra // d) % len(mem)] if ra // d < len(mem) else 0
        if wc["enable"][i]:
            if wc["write_addr"][i] == ra // d:
                collisions += 1
            mem[wc["write_addr"][i]] = m_x_cast(q["W"], p_, d, wc["data_out"][i])
        pipe = ([rdata] + pipe[:-1]) if pipe else pipe
        rdata = new_rdata
        subp = [ra % d] + subp[:-1]
        validp = [rc["enable"][i]] + validp[:-1]
        andp = [st & seen] + andp[:-1]
        seen = 0 if st else (1 if sync[i] else seen)
    if stats is not None:
        stats["collisions"] = collisions
        stats["start"] = [i for i, v in enumerate(wc["start_readout"]) if v]
    return out


def element_map(n):
    """Address of each (line, tap) word: the plan's map, from arithmetic only.
    Returns {(line, tap): (addr or None for blank, conjugated)}."""
    T = n // 2 + 1
    piv = n // 2 * T + T * n // 4
    normal, conj, m = 0, piv, {}
    for line in range(n):
        for tap in range(T):
            if line + tap < T - 1:
                if tap == 0:
                    m[(line, tap)] = (None, True)
                else:
                    m[(line, tap)] = (conj, True)
                    conj += 1
            else:
                m[(line, tap)] = (normal, False)
                normal += 1
    return m


