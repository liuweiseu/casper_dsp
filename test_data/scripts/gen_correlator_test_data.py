"""Generate test data for the Correlator modules (rtl/Correlator/).

Covered so far: Internal/cmac_acc, cmac, dual_pol_cmac, auto_tap, baseline_tap,
Internal/x_cast, Internal/read_ctrl, Internal/write_ctrl, xeng_descramble,
xeng_descramble_4ant, xeng, cross_multiplier, xeng_tvg.

Cycle-level models of the casper_library_correlator.slx diagrams. Row i of
every CSV is the value driven before / read after clock edge i (pre-edge
read convention): outputs come from the state before edge i and the inputs
of cycle i. All words are raw unsigned bit patterns, written as decimal
Python integers (dual_pol_cmac words exceed 64 bits).

Besides the structural models, every cmac / dual_pol_cmac set is checked
behaviourally: after a sync at S, the dump 2 cycles after each rst at
S + MULT + ADD + 1 + k*ACC_LEN (k >= 1) must be the exact sum of
a·conj(b) over the ACC_LEN samples S+1+(k-1)*ACC_LEN ..., with
valid_out = 1, and between dumps acc_out / valid_out relay acc_in /
valid_in with a 2-cycle delay.
"""

