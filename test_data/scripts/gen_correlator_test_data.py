def check_descramble(q, ram_lat, frames, times, out, start_cycles):
    """Behavioural check, independent of the counter structure:

    * writes: word i of a frame (line i // T, tap i % T) goes to the address of
      element_map() (blank / conjugated as there) at its arrival cycle + 2;
    * reads: after each start at s, narrow word r (r = 0 .. D*E-1, element
      r // D, block r % D from the MSB of the stored word, fields sign-extended
      to P bits) is read at s+1+r (DEL = 0) or s+1+DEL+r*(DEL+1), and appears
      on acc_out with valid_out = 1 RAM_LATENCY cycles later;
    * a read returns the RAM as left by the writes of earlier cycles.

    Returns, per readout, the elements read from the next output window's
    words. With back-to-back windows these are exactly the conjugated region
    PIVOT..E-1: the X-engine emits the wrapped-around baselines of a data
    frame (its taps' a_end inputs) in the first lines of the following
    window, and the descramble picks them up from there."""
    n, d, w, p_, T = q["N"], q["D"], q["W"], q["P"], q["T"]
    m = element_map(n)
    writes = {}
    i = 0
    for fi, words in enumerate(frames):
        for idx, x in enumerate(words):
            addr, cj = m[(idx // T, idx % T)]
            if addr is not None:
                writes.setdefault(times[i] + 2, []).append((addr, conj_swap(x, w) if cj else x, fi))
            i += 1
    ram, overwritten = {}, []
    wtimes = sorted(writes)
    per = 8 // d
    for fr, st in enumerate(start_cycles):
        rtimes = [st + 1 + r if q["DEL"] == 0 else st + 1 + q["DEL"] + r * (q["DEL"] + 1)
                  for r in range(d * q["E"])]
        src = {}
        for r, rt in enumerate(rtimes):
            for wt in wtimes:
                if wt >= rt:
                    break
                for addr, x, fi in writes[wt]:
                    ram[addr] = (x, fi)
            wtimes = [wt for wt in wtimes if wt >= rt]
            e, k = divmod(r, d)
            x, fi = ram.get(e, (0, -1))
            src[e] = fi
            fields = [s(x >> (w * (7 - f)), w) for f in range(8)]
            word = 0
            for f in fields[k * per:(k + 1) * per]:
                word = (word << p_) | u(f, p_)
            ot = rt + ram_lat
            if ot < len(out["acc_out"]):
                assert (out["acc_out"][ot], out["valid_out"][ot]) == (word, 1), (st, r, ot)
        overwritten.append(sorted(e for e, fi in src.items() if fi > fr))
    return overwritten


def xeng_stream(rng, q, frames, n_ants, acc_len, s0=6, jitter=False, burst_gap=False, neg=True,
                probes=False):
    """X-engine-like input: sync at s0, window_valid rising 2 cycles later and
    high for `frames` frames of N*ACC_LEN cycles. As at the end of the
    X-engine's tap chain, each antenna line (every ACC_LEN cycles) delivers a
    burst of T consecutive valid words. jitter: random 0..2 cycle shift of each
    burst; burst_gap: a 1-cycle hole before the last word of some bursts (the
    tap counter, enabled by (tap == T-1) | valid, then wraps early and the
    element map shifts, as in the diagram). After window_valid falls the
    bursts go on for N/2+1 more lines, as the X-engine keeps emitting the
    wrapped baselines of the last frame: negedge_delay accepts the first N/2
    lines (ceil(N/2)*ACC_LEN cycles) and gates the rest. probes: three single
    valid words around the end of that extension. Returns (acc, valid, sync,
    win, per-frame word lists, the last one partial)."""
    w, T, n = q["W"], q["T"], n_ants
    frame = n * acc_len
    w0 = s0 + 2
    cyc = w0 + (frames + 1) * frame + 2 * acc_len + 40
    acc = [rng.randrange(1 << 8 * w) for _ in range(cyc)]
    acc[0] = 0
    valid = [0] * cyc
    win = [0] * cyc
    for t in range(w0, w0 + frames * frame):
        win[t] = 1
    words, times = [], []
    for f in range(frames + 1):
        fw = []
        for line in range(n if f < frames else n // 2 + 1):
            t = w0 + 3 + f * frame + line * acc_len + (rng.randrange(3) if jitter else 0)
            for k in range(T):
                if burst_gap and line % 3 == 1 and k == T - 1:
                    t += 1
                x = rng.randrange(1 << 8 * w)
                if neg and rng.random() < 0.2:
                    # a most-negative field (its conjugate wraps)
                    j = rng.randrange(8)
                    x = (x & ~(((1 << w) - 1) << (w * j))) | ((1 << (w - 1)) << (w * j))
                acc[t] = x
                valid[t] = 1
                if f < frames or line < n // 2:     # the last tail line is gated off
                    fw.append(x)
                    times.append(t)
                t += 1
        words.append(fw)
    if probes:
        tw = w0 + frames * frame                 # window_valid falls here
        for t in (tw + q["PULSE"] - 2, tw + q["PULSE"] - 1, tw + q["PULSE"]):
            valid[t] = 1
    sync = [int(t == s0) for t in range(cyc)]
    xeng_stream.times = times
    return acc, valid, sync, win, words


