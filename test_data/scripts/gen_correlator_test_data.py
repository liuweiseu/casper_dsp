def xeng_derived(p):
    n, nb, L = p["N_ANTS"], p["N_BITS"], p["ACC_LEN"]
    m = 2 * nb + 1 + math.ceil(math.log2(L))
    q = desc_params(n, nb, L, p["DEMUX_FACTOR"])
    xd = p["ADD_LATENCY"] + p["MULT_LATENCY"] + L + math.floor(n / 2 + 1) + 1
    return m, q, xd


def m_xeng(p, sync_in, ant, window_valid, mcnt_in, stats=None):
    from gen_hold_window_test_data import m_window_delay, m_sample_and_hold
    n, L = p["N_ANTS"], p["ACC_LEN"]
    m, q, xd = xeng_derived(p)
    taps = m_tap_chain(n, L, ant, sync_in, bits=p["N_BITS"], mult=p["MULT_LATENCY"],
                       add=p["ADD_LATENCY"])
    assert taps[0]["a_end_out"] == delayed(ant, n * L), "a_end_out lag != N_ANTS*ACC_LEN"
    last = taps[-1]
    acc_d = [x & ((1 << 8 * q["W"]) - 1) for x in last["acc_out"]]
    win = m_window_delay(dict(DELAY=xd), window_valid)
    st = {} if stats is None else stats
    d_out = m_xeng_descramble(q, 2 if n == 4 else 1, acc_d, last["valid_out"],
                              last["sync_out"], win, st)
    per = n * L
    sah1 = m_sample_and_hold(dict(PERIOD=per), sync_in, mcnt_in)
    sah2 = m_sample_and_hold(dict(PERIOD=per), last["sync_out"], sah1)
    sah3 = m_sample_and_hold(dict(PERIOD=per), d_out["sync_out"], sah2)
    return dict(sync_out=d_out["sync_out"], acc=d_out["acc_out"], valid=d_out["valid_out"],
                mcnt_out=delayed(sah3, 1))


def check_xeng(p, ant, t0, out, starts):
    """End-to-end check: every complete readout is the E dual-polarisation
    visibilities of one data frame, one per baseline. Data frame f, antenna
    j, sample s is at cycle t0 + (f*N + j)*ACC_LEN + s (t0 = sync + 1).
    Returns [(frame, [(x, y) per element address])] for the checked readouts."""
    n, nb, L = p["N_ANTS"], p["N_BITS"], p["ACC_LEN"]
    _, q, _ = xeng_derived(p)
    d, P_, E = q["D"], q["P"], q["E"]
    per = 8 // d

    def pols(t):
        x = ant[t]
        xr, xi, yr, yi = unpack(x, nb, 4)
        return complex(xr, xi), complex(yr, yi)

    def vis(f, a, b):
        acc = [0j] * 4
        for s_ in range(L):
            ta = t0 + (f * n + a) * L + s_
            tb = t0 + (f * n + b) * L + s_
            ax, ay = pols(ta)
            bx, by = pols(tb)
            for i, (u_, v_) in enumerate([(ax, bx), (ay, by), (ax, by), (ay, bx)]):
                acc[i] += u_ * v_.conjugate()
        return tuple(int(c) for z in acc for c in (z.real, z.imag))

    nframes = (len(ant) - t0) // (n * L)
    table = {}
    for f in range(nframes):
        for a in range(n):
            for b in range(n):
                table.setdefault(vis(f, a, b), []).append((f, a, b))
    results = []
    for st in starts:
        words = [o for t, (o, v) in enumerate(zip(out["acc"], out["valid"])) if v and t > st]
        if len(words) < d * E:
            continue
        found = []
        for e in range(E):
            fields = []
            for k in range(d):
                w_ = words[e * d + k]
                fields += [s(w_ >> (P_ * (per - 1 - j)), P_) for j in range(per)]
            hits = table.get(tuple(fields))
            if not hits:
                found = None
                break
            found.append(hits)
        if found is None:
            continue
        frames = {h[0] for hits in found for h in hits}
        for f in sorted(frames):
            pairs = [next(((a, b) for (ff, a, b) in hits if ff == f), None) for hits in found]
            if None not in pairs and {tuple(sorted(x)) for x in pairs} == {
                    (x, y) for x in range(n) for y in range(x, n)}:
                results.append((f, pairs))
                break
    return results



