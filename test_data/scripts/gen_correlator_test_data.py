# ── helpers ──────────────────────────────────────────────────────────────────
def s(x, n):
    """Raw n-bit word -> signed int."""
    x &= (1 << n) - 1
    return x - (1 << n) if x >> (n - 1) else x


def u(x, n):
    return x & ((1 << n) - 1)


def pack(parts, n):
    """[p0, p1, ...] signed ints -> raw word, p0 in the MSBs."""
    w = 0
    for p in parts:
        w = (w << n) | u(p, n)
    return w


def unpack(w, n, k):
    """Raw word -> k signed parts, MSB part first."""
    return [s(w >> (n * (k - 1 - i)), n) for i in range(k)]


def delayed(seq, d, fill=0):
    return [fill] * d + seq[:len(seq) - d] if d else list(seq)


def write_set(d, params, ports):
    d.mkdir(parents=True, exist_ok=True)
    (d / "params.json").write_text(json.dumps(params, indent=2) + "\n")
    for name, vals in ports.items():
        vals = list(vals)
        if vals and isinstance(vals[0], list):
            # array port: one file per element, sim_<name><j>.csv = element j
            for j in range(len(vals[0])):
                (d / f"sim_{name}{j}.csv").write_text("".join(f"{int(v[j])}\n" for v in vals))
        else:
            (d / f"sim_{name}.csv").write_text("".join(f"{int(v)}\n" for v in vals))


def toml_block(dir_, top, sets):
    lines = [f"# test {top}", "[[simulations]]", f'dir = "{dir_}"', f'top = "{top}"',
             f'test_data_script = "{SCRIPT}"']
    for p, desc in sets:
        lines += [f"# {desc}", "[[simulations.parameters]]"]
        lines += [f"{k} = {v}" for k, v in p.items()]
    return "\n".join(lines)


def write_md(mdir, top, prose, sets, cycles):
    keys = list(sets[0][0].keys())
    lines = [f"# {top} test data", "", prose, "",
             f"Generated by `test_data/scripts/{SCRIPT}` from a cycle-level model of the "
             "casper_library diagram (not exported from MATLAB). Each `simdataN/` holds "
             "`params.json` (the testbench matches it against the DUT parameters) and one "
             "`sim_<port>.csv` per port: raw unsigned words in decimal, row i = value "
             "driven before / read after clock edge i.", "",
             "| Test # | Directory | " + " | ".join(keys) + " | Cycles | Description |",
             "|" + "---|" * (len(keys) + 4)]
    for n, (p, desc) in enumerate(sets):
        lines.append(f"| {n} | `simdata{n}` | " + " | ".join(str(p[k]) for k in keys)
                     + f" | {cycles[n]} | {desc} |")
    (mdir / "test_data.md").write_text("\n".join(lines) + "\n")


# ── cmac_acc ─────────────────────────────────────────────────────────────────
def m_cmac_acc(n, rst, din, acc_in, valid_in):
    """Raw words in, (acc_out, valid_out) raw words out."""
    q = 0
    pd = [0, 0]
    pv = [0, 0]
    acc_out, valid_out = [], []
    for r, x, ai, vi in zip(rst, din, acc_in, valid_in):
        acc_out.append(pd[1])
        valid_out.append(pv[1])
        pd = [q if r else ai, pd[0]]
        pv = [1 if r else vi, pv[0]]
        q = x if r else u(q + x, n)
    return acc_out, valid_out


def gen_cmac_acc():
    mdir = TEST_DATA_ROOT / CATEGORY / "Internal" / "cmac_acc"
    specs = [(dict(N_BITS=16), "16-bit, random rst (single, back-to-back, long gaps)"),
             (dict(N_BITS=6), "6-bit: the accumulator wraps"),
             (dict(N_BITS=1), "1-bit")]
    sets, cycles = [], []
    for k, (p, desc) in enumerate(specs):
        rng = random.Random(f"cmac_acc-{k}")
        n, cyc = p["N_BITS"], 400
        rst = [0] * cyc
        t = 3
        while t < cyc:
            rst[t] = 1
            t += rng.choice([1, 2, 5, 17, 40])
        din = [rng.randrange(1 << n) for _ in range(cyc)]
        acc_in = [rng.randrange(1 << n) for _ in range(cyc)]
        valid_in = [rng.randrange(2) for _ in range(cyc)]
        acc_out, valid_out = m_cmac_acc(n, rst, din, acc_in, valid_in)
        write_set(mdir / f"simdata{k}", p, dict(rst=rst, din=din, acc_in=acc_in,
                                                valid_in=valid_in, acc_out=acc_out,
                                                valid_out=valid_out))
        sets.append((p, desc))
        cycles.append(cyc)
    write_md(mdir, "cmac_acc",
             "`cmac_acc` is the accumulate-and-relay cell of `cmac` (`system_871`/`886`): "
             "`q <= rst ? din : q + din` (Xilinx Accumulator with hasbypass), "
             "`acc_out = rst ? q : acc_in` and `valid_out = rst ? 1 : valid_in`, both "
             "delayed 2 cycles.", sets, cycles)
    return toml_block("Correlator/Internal", "cmac_acc", sets)


# ── cmac ─────────────────────────────────────────────────────────────────────
def cmac_widths(p):
    bg = math.ceil(math.log2(p["ACC_LEN"]))
    return bg, p["N_BITS_A"] + p["N_BITS_B"] + 1 + bg


def m_cmac(p, a, b, acc_in, sync, valid_in):
    """Structural model of cmac. Returns (acc_out, valid_out, rst)."""
    na, nb = p["N_BITS_A"], p["N_BITS_B"]
    bg, m = cmac_widths(p)
    lat = p["MULT_LATENCY"] + p["ADD_LATENCY"]
    # cmult: a·conj(b), exact, latency lat (power-on 0)
    pre, pim = [], []
    for x, y in zip(a, b):
        ar, ai = unpack(x, na, 2)
        br, bi = unpack(y, nb, 2)
        pre.append(u(ar * br + ai * bi, m))
        pim.append(u(ai * br - ar * bi, m))
    pre, pim = delayed(pre, lat), delayed(pim, lat)
    # sync -> Delay(lat-1) -> Counter -> (cnt == 0, latency 1)
    sync_d = delayed(sync, lat - 1)
    cnt, rst, prev_zero = 0, [], 0
    for sd in sync_d:
        rst.append(prev_zero)
        prev_zero = int(cnt == 0)
        cnt = 0 if sd or cnt == p["ACC_LEN"] - 1 else cnt + 1
    ai_re = [w >> m for w in acc_in]
    ai_im = [u(w, m) for w in acc_in]
    re, _ = m_cmac_acc(m, rst, pre, ai_re, [0] * len(a))
    im, valid_out = m_cmac_acc(m, rst, pim, ai_im, valid_in)
    return [(r << m) | i for r, i in zip(re, im)], valid_out, rst


def check_cmac(p, a, b, acc_in, sync, valid_in, acc_out, valid_out, rst):
    """Behavioural check of the dumps after the first sync (see module doc)."""
    na, nb = p["N_BITS_A"], p["N_BITS_B"]
    _, m = cmac_widths(p)
    L, lat = p["ACC_LEN"], p["MULT_LATENCY"] + p["ADD_LATENCY"]
    syncs = [t for t, v in enumerate(sync) if v]
    S = syncs[0]
    nxt = syncs[1] if len(syncs) > 1 else len(a)
    dumps = {S + lat + 1 + k * L + 2 for k in range(1, len(a))}
    checked = 0
    for t in range(S + lat + 3, min(len(a), nxt + lat + 1)):
        if t == S + lat + 3:
            # first rst after sync: dumps the partial sum from before sync
            assert valid_out[t] == 1, (p, t)
        elif t in dumps:
            k = (t - 2 - (S + lat + 1)) // L
            first = S + 1 + (k - 1) * L
            sre = sim = 0
            for j in range(first, first + L):
                ar, ai = unpack(a[j], na, 2)
                br, bi = unpack(b[j], nb, 2)
                sre += ar * br + ai * bi
                sim += ai * br - ar * bi
            assert (acc_out[t], valid_out[t]) == (pack([sre, sim], m), 1), (p, t)
            checked += 1
        else:
            assert (acc_out[t], valid_out[t]) == (acc_in[t - 2], valid_in[t - 2]), (p, t)
    assert checked >= 3, (p, checked)
    return checked


def cmac_stim(rng, p, cyc, syncs):
    na, nb = p["N_BITS_A"], p["N_BITS_B"]
    _, m = cmac_widths(p)
    L = p["ACC_LEN"]
    a, b = [], []
    for t in range(cyc):
        if syncs[0] + 1 + L <= t < syncs[0] + 1 + 2 * L:
            # one whole integration of most-negative inputs: maximum growth
            a.append(pack([-(1 << (na - 1))] * 2, na))
            b.append(pack([-(1 << (nb - 1))] * 2, nb))
        else:
            a.append(rng.randrange(1 << 2 * na))
            b.append(rng.randrange(1 << 2 * nb))
    acc_in = [rng.randrange(1 << 2 * m) for _ in range(cyc)]
    valid_in = [rng.randrange(2) for _ in range(cyc)]
    sync = [int(t in syncs) for t in range(cyc)]
    return a, b, acc_in, sync, valid_in


CMAC_KEYS = ["ACC_LEN", "N_BITS_A", "BIN_PT_A", "N_BITS_B", "BIN_PT_B",
             "MULT_LATENCY", "ADD_LATENCY", "MULTIPLIER_IMPLEMENTATION"]


def P(keys, vals):
    return dict(zip(keys, vals))


def gen_cmac():
    mdir = TEST_DATA_ROOT / CATEGORY / "cmac"
    specs = [
        (P(CMAC_KEYS, [128, 4, 3, 4, 3, 1, 1, 2]), "Mask defaults: acc_len 128, Fix_4_3, latency 1+1"),
        (P(CMAC_KEYS, [4, 4, 3, 4, 3, 1, 0, 2]), "acc_len 4, add latency 0 (sync delay 0)"),
        (P(CMAC_KEYS, [10, 8, 7, 8, 7, 3, 2, 0]), "acc_len 10 (not a power of 2), Fix_8_7, latency 3+2"),
        (P(CMAC_KEYS, [16, 6, 5, 8, 7, 0, 1, 1]), "Unequal widths Fix_6_5 × Fix_8_7, mult latency 0"),
        (P(CMAC_KEYS, [2, 4, 3, 4, 3, 2, 1, 2]), "Smallest acc_len 2"),
    ]
    sets, cycles = [], []
    for k, (p, desc) in enumerate(specs):
        rng = random.Random(f"cmac-{k}")
        L = p["ACC_LEN"]
        cyc = 6 * L + 60 if L > 16 else 400
        s0 = 7
        # a second sync, not aligned to the integration grid, realigns the rst phase
        syncs = [s0, s0 + 4 * L + 3] if L > 16 else [s0, s0 + 9 * L + 1 + (L // 2)]
        a, b, acc_in, sync, valid_in = cmac_stim(rng, p, cyc, syncs)
        acc_out, valid_out, rst = m_cmac(p, a, b, acc_in, sync, valid_in)
        check_cmac(p, a, b, acc_in, sync, valid_in, acc_out, valid_out, rst)
        write_set(mdir / f"simdata{k}", p, dict(a=a, b=b, acc_in=acc_in, sync=sync,
                                                valid_in=valid_in, acc_out=acc_out,
                                                valid_out=valid_out))
        sets.append((p, desc))
        cycles.append(cyc)
    write_md(mdir, "cmac",
             "`cmac` accumulates `a·conj(b)` over `ACC_LEN` samples and inserts each "
             "integration into the `acc_in` relay. Each set has a sync near the start, a "
             "whole integration of most-negative inputs (maximum bit growth) and a "
             "second, misaligned sync that realigns the integration phase; `acc_in` and "
             "`valid_in` are random. The generator checks every dump against the exact "
             "sum of `a·conj(b)` over its `ACC_LEN` samples, and every other cycle "
             "against the 2-cycle relay of `acc_in` / `valid_in`.", sets, cycles)
    return toml_block(CATEGORY, "cmac", sets)


# ── dual_pol_cmac ────────────────────────────────────────────────────────────
DP_PAIRS = [(0, 0), (1, 1), (0, 1), (1, 0)]  # (a1 pol, a2 pol): XX, YY, XY, YX


def m_dual_pol_cmac(p, a1, a2, acc_in, sync, valid_in, check=True):
    n = p["N_BITS_IN"]
    cp = dict(ACC_LEN=p["ACC_LEN"], N_BITS_A=n, BIN_PT_A=n - 1, N_BITS_B=n,
              BIN_PT_B=n - 1, MULT_LATENCY=p["MULT_LATENCY"], ADD_LATENCY=p["ADD_LATENCY"])
    _, m = cmac_widths(cp)
    outs, valid_out = [], None
    for c, (pa, pb) in enumerate(DP_PAIRS):
        a = [(w >> (2 * n * (1 - pa))) & ((1 << 2 * n) - 1) for w in a1]
        b = [(w >> (2 * n * (1 - pb))) & ((1 << 2 * n) - 1) for w in a2]
        ai = [(w >> (2 * m * (3 - c))) & ((1 << 2 * m) - 1) for w in acc_in]
        vi = valid_in if c == 3 else [0] * len(a1)
        o, v, _ = m_cmac(cp, a, b, ai, sync, vi)
        if check:
            check_cmac(cp, a, b, ai, sync, vi, o, v, None)
        outs.append(o)
        if c == 3:
            valid_out = v
    acc_out = [(w0 << 6 * m) | (w1 << 4 * m) | (w2 << 2 * m) | w3 for w0, w1, w2, w3 in zip(*outs)]
    return acc_out, valid_out, m


def gen_dual_pol_cmac():
    mdir = TEST_DATA_ROOT / CATEGORY / "dual_pol_cmac"
    keys = ["ACC_LEN", "N_BITS_IN", "BIN_PT_IN", "MULT_LATENCY", "ADD_LATENCY",
            "MULTIPLIER_IMPLEMENTATION"]
    specs = [
        (P(keys, [128, 4, 3, 1, 1, 2]), "Mask defaults: acc_len 128, 4-bit inputs"),
        (P(keys, [8, 4, 3, 2, 1, 2]), "acc_len 8, latency 2+1"),
        (P(keys, [6, 8, 7, 1, 0, 0]), "acc_len 6, 8-bit inputs, add latency 0"),
    ]
    sets, cycles = [], []
    for k, (p, desc) in enumerate(specs):
        rng = random.Random(f"dual_pol_cmac-{k}")
        n, L = p["N_BITS_IN"], p["ACC_LEN"]
        cyc = 6 * L + 60 if L > 16 else 300
        s0 = 5
        syncs = [s0, s0 + 4 * L + 3] if L > 16 else [s0, s0 + 9 * L + 1 + (L // 2)]
        neg = pack([-(1 << (n - 1))] * 4, n)
        a1, a2 = [], []
        for t in range(cyc):
            if s0 + 1 + L <= t < s0 + 1 + 2 * L:
                a1.append(neg)
                a2.append(neg)
            else:
                a1.append(rng.randrange(1 << 4 * n))
                a2.append(rng.randrange(1 << 4 * n))
        m = 2 * n + 1 + math.ceil(math.log2(L))
        acc_in = [rng.randrange(1 << 8 * m) for _ in range(cyc)]
        valid_in = [rng.randrange(2) for _ in range(cyc)]
        sync = [int(t in syncs) for t in range(cyc)]
        acc_out, valid_out, _ = m_dual_pol_cmac(p, a1, a2, acc_in, sync, valid_in)
        write_set(mdir / f"simdata{k}", p, dict(a1=a1, a2=a2, acc_in=acc_in, sync=sync,
                                                valid_in=valid_in, acc_out=acc_out,
                                                valid_out=valid_out))
        sets.append((p, desc))
        cycles.append(cyc)
    write_md(mdir, "dual_pol_cmac",
             "`dual_pol_cmac` runs four `cmac`s on the polarisation products "
             "`{XX, YY, XY, YX}` = `{a1.p0·conj(a2.p0), a1.p1·conj(a2.p1), "
             "a1.p0·conj(a2.p1), a1.p1·conj(a2.p0)}` (p0 in the MSBs of a1/a2; "
             "acc_in/acc_out slices in the same order, XX in the MSBs). Only the YX "
             "cmac sees `valid_in` and drives `valid_out`. Stimulus and the per-cmac "
             "behavioural check are as for `cmac`.", sets, cycles)
    return toml_block(CATEGORY, "dual_pol_cmac", sets)


# ── auto_tap / baseline_tap ──────────────────────────────────────────────────
MULT_IMP = {0: 0, 1: 2, 2: 1}  # tap mult_type -> dual_pol_cmac multiplier_implementation


def m_sync_delay(seq, n):
    """casper sync_delay (rtl/Delays/sync_delay.sv): a pulse restarts the count."""
    if n == 0:
        return list(seq)
    cnt, out = 0, []
    for x in seq:
        out.append(int(cnt == 1))
        cnt = n if x else (cnt - 1 if cnt else 0)
    return out


def tap_dp(p):
    return dict(ACC_LEN=p["ACC_LEN"], N_BITS_IN=p["N_BITS"], BIN_PT_IN=p["N_BITS"] - 1,
                MULT_LATENCY=p["MULT_LATENCY"], ADD_LATENCY=p["ADD_LATENCY"],
                MULTIPLIER_IMPLEMENTATION=MULT_IMP[p["MULT_TYPE"]])


def auto_tap_delays(p):
    n, L = p["N_ANTS"], p["ACC_LEN"]
    d = (L - 1) * math.ceil(n / 2) + math.ceil(n / 2) - n // 2
    s_ = p["ADD_LATENCY"] + p["MULT_LATENCY"] + L + math.floor(n / 2 + 1) + 1
    return d, s_


def m_auto_tap(p, a_del, a_ndel, a_loop, acc_in, valid_in, sync_in, check=True):
    d, s_ = auto_tap_delays(p)
    acc_out, valid_out, _ = m_dual_pol_cmac(tap_dp(p), a_del, a_ndel, acc_in, sync_in,
                                            valid_in, check)
    return dict(a_del_out=list(a_del), a_ndel_out=list(a_ndel), a_end_out=delayed(a_loop, d),
                acc_out=acc_out, valid_out=valid_out, rst_out=list(sync_in),
                sync_out=m_sync_delay(sync_in, s_))


def m_baseline_tap(p, a_del, a_ndel, a_end, acc_in, valid_in, rst, sync1, check=True):
    n, L, sep = p["N_ANTS"], p["ACC_LEN"], p["ANT_SEP"]
    a_del_out = delayed(a_del, L + 1)
    rst_out = delayed(rst, 1)
    cnt, sel = 0, []
    for r in rst:
        sel.append(int(cnt < sep * L))
        cnt = 0 if r or cnt == n * L - 1 else cnt + 1
    a2 = delayed([e if sl else nd for sl, nd, e in zip(sel, a_ndel, a_end)], 1)
    acc_out, valid_out, _ = m_dual_pol_cmac(tap_dp(p), a_del_out, a2, acc_in, rst_out,
                                            valid_in, check)
    return dict(a_del_out=a_del_out, a_ndel_out=delayed(a_ndel, 1), a_end_out=delayed(a_end, 1),
                acc_out=acc_out, valid_out=valid_out, rst_out=rst_out, sync_out=list(sync1))


def m_tap_chain(n_ants, L, ant, sync, bits=4, mult=2, add=1, a_loop_check=True):
    """xeng tap chain (xeng_init.m wiring): auto_tap + floor(N/2) baseline_taps,
    tapK.a_del_out looped back to auto_tap.a_loop. Returns the per-tap outputs."""
    base = dict(N_ANTS=n_ants, N_BITS=bits, ACC_LEN=L, ADD_LATENCY=add, MULT_LATENCY=mult,
                MULT_TYPE=0)
    k_taps = n_ants // 2
    zeros = [0] * len(ant)
    # a_del path first: it does not depend on the loop
    a_del = [list(ant)]
    for k in range(1, k_taps + 1):
        a_del.append(delayed(a_del[-1], L + 1))
    taps = [m_auto_tap(dict(base), ant, ant, a_del[-1], zeros, zeros, sync, check=False)]
    for k in range(1, k_taps + 1):
        prev = taps[-1]
        taps.append(m_baseline_tap(dict(base, ANT_SEP=k), prev["a_del_out"], prev["a_ndel_out"],
                                   prev["a_end_out"], prev["acc_out"], prev["valid_out"],
                                   prev["rst_out"], prev["sync_out"], check=False))
    return taps


def check_tap_chain(n_ants, L, frames=4, seed=0):
    """Composition check of the tap models, ahead of xeng (C6):

    * a_end_out of the auto_tap lags the antenna stream by exactly N_ANTS*ACC_LEN;
    * every integration a tap feeds into the relay pairs two antennas' samples
      of the same time samples (same frame, same sample index), i.e. it is a
      baseline visibility, and per frame the taps produce N_ANTS*(N_ANTS/2+1)
      of them covering every baseline.

    The antenna stream is frame-major: frame f, antenna j, sample s at cycle
    S + 1 + (f*N_ANTS + j)*ACC_LEN + s. Each sample word encodes (f, j, s) so
    the paired samples can be read back from the cmac inputs.
    """
    rng = random.Random(seed)
    n = n_ants
    S = 3
    cyc = S + 1 + (frames + 2) * n * L
    bits = 2 * max(8, (frames * n * L).bit_length() + 2)
    # tag: one polarisation's re = index (f*N + j)*L + s, so products identify samples
    ant, tag = [], {}
    for t in range(cyc):
        i = t - (S + 1)
        ant.append(i if i >= 0 else 0)
    taps = m_tap_chain(n, L, ant, [int(t == S) for t in range(cyc)], bits=bits)
    assert taps[0]["a_end_out"] == delayed(ant, n * L), "loop delay != N_ANTS*ACC_LEN"
    # replay the cmac inputs of every tap and check the pairing of each window
    k_taps = n // 2
    pairs = {}
    for k in range(k_taps + 1):
        if k == 0:
            a1, a2, sy = ant, ant, [int(t == S) for t in range(cyc)]
        else:
            a1 = delayed(ant, k * (L + 1))
            prev_ndel = delayed(ant, k - 1)
            prev_end = delayed(ant, n * L + k - 1)
            rst = delayed([int(t == S) for t in range(cyc)], k - 1)
            cnt, sel = 0, []
            for r in rst:
                sel.append(int(cnt < k * L))
                cnt = 0 if r or cnt == n * L - 1 else cnt + 1
            a2 = delayed([e if sl else nd for sl, nd, e in zip(sel, prev_ndel, prev_end)], 1)
            sy = delayed(rst, 1)
        start = sy.index(1) + 1                 # cmac frame start
        for w in range(1, frames * n):          # integration windows (skip the first)
            idx1 = [a1[start + w * L + s_] for s_ in range(L)]
            idx2 = [a2[start + w * L + s_] for s_ in range(L)]
            if 0 in idx1 or 0 in idx2:
                continue                        # touches the power-on zeros
            fj1 = {(i // L) for i in idx1}
            fj2 = {(i // L) for i in idx2}
            ss1 = [i % L for i in idx1]
            ss2 = [i % L for i in idx2]
            assert len(fj1) == 1 and len(fj2) == 1 and ss1 == ss2 == list(range(L)), (n, L, k, w)
            (b1,), (b2,) = fj1, fj2
            f1, j1 = divmod(b1, n)
            f2, j2 = divmod(b2, n)
            assert f1 == f2, f"tap {k} window {w} pairs frames {f1} and {f2}"
            pairs.setdefault(f1, []).append((k, j1, j2))
    for f, lst in pairs.items():
        if len(lst) == n * (k_taps + 1):
            base = {tuple(sorted((j1, j2))) for _, j1, j2 in lst}
            assert base == {(x, y) for x in range(n) for y in range(x, n)}, (n, L, f, lst)
    return pairs


def tap_stim(rng, n_bits, cyc, frame, s0, n_ants_frames_neg=True):
    w = 4 * n_bits
    neg = pack([-(1 << (n_bits - 1))] * 4, n_bits)
    out = []
    for t in range(cyc):
        out.append(neg if s0 + 1 + frame <= t < s0 + 1 + 2 * frame else rng.randrange(1 << w))
    # cycle 0 is read at the t = 0 edge, before the first inputs reach the
    # combinational pass-through outputs: keep it 0
    out[0] = 0
    return out


