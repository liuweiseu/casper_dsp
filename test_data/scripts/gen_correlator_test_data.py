TVG_CONST = 0x1A4E   # {0.1 -> 0.125, -0.75, 0.5, -0.25} as Fix_4_3


def m_xeng_tvg(p, tvg_sel, sync, data_in, valid_in, tv):
    X, SP = p["X_INT_BITS"], p["SYNC_PERIOD"]
    rel = use = sel_d = 0
    cnt4, e2_prev = (1 << SP) - 2, 0
    cnt, ant_prev, rst_d = 0, 0, 0
    c1, c2, c3 = 0, 0, 15
    dpipe, concat1_d, mux2, mux3 = [0, 0], 0, 0, 0
    vpipe, spipe = [0, 0, 0], [0, 0]
    out = dict(sync_out=[], data_out=[], valid_out=[])
    for ts, sy, di, vi in zip(tvg_sel, sync, data_in, valid_in):
        msb4 = (cnt4 >> SP) & 1
        edge2 = msb4 ^ e2_prev
        sync_int = edge2 if use else sy
        msbc = (cnt >> X) & 1
        ant_en = msbc ^ ant_prev
        out["data_out"].append(mux3)
        out["valid_out"].append(vpipe[2])
        out["sync_out"].append(spipe[1])
        mux3 = [dpipe[1], concat1_d, TVG_CONST, mux2][sel_d]
        mux2 = tv[c2] & 0xFFFF
        concat1_d = (c1 << 12) | (c3 << 8) | (c1 << 4) | c3
        dpipe = [di, dpipe[0]]
        if rst_d:
            c1, c2, c3 = 0, 0, 15
        elif ant_en:
            c1, c2, c3 = (c1 + 1) % 16, (c2 + 1) % 8, (c3 - 1) % 16
        vpipe = [1 if use else vi, vpipe[0], vpipe[1]]
        spipe = [rst_d, spipe[0]]
        rst_d = sync_int
        cnt = 0 if sync_int else (cnt + 1) % (1 << (X + 1))
        ant_prev, e2_prev = msbc, msb4
        cnt4 = (cnt4 + 1) % (1 << (SP + 1))
        use, rel, sel_d = rel, int(ts != 0), ts
    return out


