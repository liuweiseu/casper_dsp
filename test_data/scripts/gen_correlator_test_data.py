    specs = [(P(keys, [2, 5, 15, 16]), "Mask defaults (internal sync period 2^15: one pulse at t = 2)"),
             (P(keys, [2, 2, 6, 16]), "X_INT_BITS 2, SYNC_PERIOD 6: several internal syncs per mode"),
             (P(keys, [4, 3, 8, 24]), "24-bit data_in (data_out 24 bits)"),
             (P(keys, [2, 1, 1, 8]), "Smallest periods, 8-bit data_in (data_out 16 bits)")]
    sets, cycles = [], []
    for k, (p, desc) in enumerate(specs):
        rng = random.Random(f"xeng_tvg-{k}")
        cyc = 1600
        X = p["X_INT_BITS"]
        # mode schedule: 0 (external sync / data), 1, 2, 3, 0, 3 with sync pulses
        sched = [0] * 200 + [1] * 400 + [2] * 150 + [3] * 450 + [0] * 150 + [3] * 250
        tvg_sel = sched[:cyc]
        tvg_sel[0] = 0
        sync = [int(t in (20, 90, 700, 1320)) for t in range(cyc)]
        data_in = [0] + [rng.randrange(1 << p["DATA_WIDTH"]) for _ in range(cyc - 1)]
        valid_in = [0] + [rng.randrange(2) for _ in range(cyc - 1)]
        tv = [(rng.randrange(1 << 16) << 16) | (0x1111 * j) for j in range(8)]
        out = m_xeng_tvg(p, tvg_sel, sync, data_in, valid_in, tv)
        # behavioural checks
        if k == 1:
            # mode 1: after an internal sync at t0 (sync_out at t0+3), data_out(t0+4)
            # is antenna 0 = {0, 15, 0, 15}, then a new antenna every 2^X cycles
            so = [t for t, v in enumerate(out["sync_out"]) if v and 210 < t < 590]
            assert so, "no internal sync in mode 1"
            t0 = so[0] - 3
            for a in range(4):
                c = a % 16
                assert out["data_out"][t0 + 4 + a * (1 << X)] == (c << 12) | ((15 - c) << 8) | (c << 4) | (15 - c)
            so3 = [t for t, v in enumerate(out["sync_out"]) if v and 760 < t < 1190]
            t0 = so3[0] - 3
            for a in range(9):
                assert out["data_out"][t0 + 4 + a * (1 << X)] == 0x1111 * (a % 8)
        assert TVG_CONST in out["data_out"][610:740]
        write_set(mdir / f"simdata{k}", p, dict(tvg_sel=tvg_sel, sync=sync, data_in=data_in,
                                                valid_in=valid_in, tv=[list(tv)] * cyc, **out))
        sets.append((p, desc))
        cycles.append(cyc)
    write_md(mdir, "xeng_tvg",
             "`xeng_tvg` selects the X-engine input: 0 pass-through, 1 antenna counter "
             "pattern {c, ~c, c, ~c}, 2 the constant 0x1A4E, 3 tv[k][15:0] per antenna. "
             "Stimulus: the mode sequence 0, 1, 2, 3, 0, 3 with external sync pulses, "
             "random data / valid, tv[k] = (random << 16) | 0x1111*k (only the low 16 bits "
             "may appear). `tv` has one file per register: `sim_tv<k>.csv` is tv[k]. Set 1 checks the mode-1 and mode-3 antenna sequences after an "
             "internal sync (antenna 0 at sync_out + 1, then every 2^X_INT_BITS cycles).",
             sets, cycles)
    return toml_block(CATEGORY, "xeng_tvg", sets)


